/**
 * VoiceGuard Vercel / Static Build Helper
 * =======================================
 * Generates config.js during deployment to inject VITE_API_BASE_URL or API_BASE_URL.
 */
const fs = require('fs');
const path = require('path');

const apiUrl = (process.env.VITE_API_BASE_URL || process.env.API_BASE_URL || process.env.NEXT_PUBLIC_API_BASE_URL || '').trim().replace(/\/+$/, '');

console.log('[VoiceGuard Build] Running frontend build step...');
console.log(`[VoiceGuard Build] Configured Backend URL: ${apiUrl || '(None configured - will use auto-detection / localStorage)'}`);

const configContent = `/**
 * VoiceGuard Frontend Runtime Configuration
 * Generated by build step. Can be overridden in UI settings or via localStorage.
 */
(function() {
    'use strict';
    window.__VOICEGUARD_CONFIG__ = {
        API_BASE_URL: ${JSON.stringify(apiUrl)}
    };
    window.getVoiceGuardApiBaseUrl = function() {
        try {
            var userSaved = localStorage.getItem('voiceguard_api_url');
            if (userSaved && userSaved.trim()) return userSaved.trim().replace(/\\/+$/, '');
        } catch (e) {}
        if (window.__VOICEGUARD_CONFIG__ && window.__VOICEGUARD_CONFIG__.API_BASE_URL) {
            return window.__VOICEGUARD_CONFIG__.API_BASE_URL;
        }
        if (typeof window !== 'undefined' && window.ENV) {
            var envUrl = window.ENV.VITE_API_BASE_URL || window.ENV.API_BASE_URL;
            if (envUrl && envUrl.trim()) return envUrl.trim().replace(/\\/+$/, '');
        }
        var hostname = window.location.hostname;
        if (hostname === 'localhost' || hostname === '127.0.0.1' || window.location.protocol === 'file:') {
            if (window.location.port === '8000') return window.location.origin;
            return 'http://localhost:8000';
        }
        return 'https://fieldproj-v2.onrender.com';
    };
})();
`;

fs.writeFileSync(path.join(__dirname, 'config.js'), configContent, 'utf-8');
console.log('[VoiceGuard Build] config.js generated successfully.');
