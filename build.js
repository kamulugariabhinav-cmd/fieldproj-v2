/**
 * VoiceGuard Vercel / Static Build Helper
 * =======================================
 * Generates config.js during deployment to inject VITE_API_BASE_URL or API_BASE_URL.
 */
const fs = require('fs');
const path = require('path');

const apiUrl = (process.env.VITE_API_BASE_URL || process.env.API_BASE_URL || process.env.NEXT_PUBLIC_API_BASE_URL || '').trim().replace(/\/+$/, '');

console.log('[VoiceGuard Build] Running frontend build step...');
console.log('[VoiceGuard Build] Configured Backend URL: ' + (apiUrl || '(None configured - will use auto-detection / localStorage)'));

const configContent = '/**\n' +
' * VoiceGuard Frontend Runtime Configuration\n' +
' * Generated by build step. Can be overridden in UI settings or via localStorage.\n' +
' */\n' +
'(function() {\n' +
'    \'use strict\';\n\n' +
'    var PRODUCTION_API_URL = \'https://fieldproj-v2.onrender.com\';\n' +
'    var LOCAL_API_URL = \'http://localhost:8000\';\n\n' +
'    window.__VOICEGUARD_CONFIG__ = {\n' +
'        API_BASE_URL: ' + JSON.stringify(apiUrl) + '\n' +
'    };\n\n' +
'    window.getVoiceGuardApiBaseUrl = function() {\n' +
'        var isLocal = false;\n' +
'        try {\n' +
'            var hostname = window.location.hostname;\n' +
'            isLocal = (hostname === \'localhost\' || hostname === \'127.0.0.1\' || window.location.protocol === \'file:\');\n' +
'        } catch (e) {}\n\n' +
'        // 1. User-saved custom URL from localStorage\n' +
'        try {\n' +
'            var userSaved = localStorage.getItem(\'voiceguard_api_url\');\n' +
'            if (userSaved && typeof userSaved === \'string\') {\n' +
'                userSaved = userSaved.trim().replace(/\\/+$/, \'\');\n\n' +
'                if (!isLocal) {\n' +
'                    var isStaleLocal = userSaved.indexOf(\'localhost\') !== -1 || userSaved.indexOf(\'127.0.0.1\') !== -1;\n' +
'                    var isSameOrigin = (window.location && window.location.origin && userSaved === window.location.origin);\n' +
'                    var isMixedContent = (window.location.protocol === \'https:\' && userSaved.indexOf(\'http://\') === 0 && !isStaleLocal);\n\n' +
'                    if (isStaleLocal || isSameOrigin || isMixedContent) {\n' +
'                        try { localStorage.removeItem(\'voiceguard_api_url\'); } catch (err) {}\n' +
'                        userSaved = null;\n' +
'                    }\n' +
'                }\n\n' +
'                if (userSaved && userSaved.length > 0) {\n' +
'                    return userSaved;\n' +
'                }\n' +
'            }\n' +
'        } catch (e) {}\n\n' +
'        // 2. Build-time injected configuration\n' +
'        if (window.__VOICEGUARD_CONFIG__ && window.__VOICEGUARD_CONFIG__.API_BASE_URL) {\n' +
'            var cfg = window.__VOICEGUARD_CONFIG__.API_BASE_URL.trim().replace(/\\/+$/, \'\');\n' +
'            if (cfg) return cfg;\n' +
'        }\n\n' +
'        // 3. Runtime window.ENV configuration\n' +
'        if (typeof window !== \'undefined\' && window.ENV) {\n' +
'            var envUrl = window.ENV.VITE_API_BASE_URL || window.ENV.API_BASE_URL;\n' +
'            if (envUrl && envUrl.trim()) return envUrl.trim().replace(/\\/+$/, \'\');\n' +
'        }\n\n' +
'        // 4. Local development default\n' +
'        if (isLocal) {\n' +
'            if (window.location.port === \'8000\') return window.location.origin;\n' +
'            return LOCAL_API_URL;\n' +
'        }\n\n' +
'        // 5. Production deployment default\n' +
'        return PRODUCTION_API_URL;\n' +
'    };\n' +
'})();\n';

fs.writeFileSync(path.join(__dirname, 'config.js'), configContent, 'utf-8');
console.log('[VoiceGuard Build] config.js generated successfully.');
